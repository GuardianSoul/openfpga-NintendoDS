def main():
    out = []
    out.append("/* Generated by tools/ds-tests/mkfont.py: 8x8 font, ASCII 0x20-0x5F,")
    out.append("   one byte per row, bit 7 = leftmost pixel. */")
    out.append("const unsigned char font8x8[64][8] = {")
    for c in range(0x20, 0x60):
        rows = G[chr(c)]
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(c)
        bs = []
        for r in rows + ["     "]:
            b = 0
            for x, ch in enumerate(r):
                if ch == '#':
                    b |= 0x80 >> (x + 1)
            bs.append(b)
        out.append("    {" + ",".join(f"0x{b:02X}" for b in bs) + "}, /* " +
                   repr(chr(c)).replace("*/", "* /") + " */")
    out.append("};")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
