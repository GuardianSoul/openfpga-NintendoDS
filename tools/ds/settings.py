#!/usr/bin/env python3
"""Core Settings of the DS core: the single source for the menu and the RTL.

    settings.py --svh rtl/pocket/nds_settings.svh     write the RTL header
    settings.py --check rtl/pocket/nds_settings.svh   exit 1 if it is stale

tools/ds/package.py builds interact.json from SETTINGS; core_top_ds.sv
decodes the bridge writes with the generated header, so the menu and the
core cannot drift (openfpga-PlayStation's pattern: docs/pocket-stick-settings.md).

Each row: (name, APF variable id, bridge address, packet bit, width,
default value, [(value, option label), ...]). APF's defaultval is the
option's position, so package.py looks it up from the default value. A
list whose options are reordered gets a new id, so a saved position resets
to the default instead of picking another option. Labels are Title Case
and at most MAX_LABEL characters: the Pocket's menu cut "L: Layout | R:
Touch Mode" after 19 (#217), in a proportional font.
"""
import argparse
import sys

# Touch Button (id 2) and Screen Layout (id 4) were removed (#217): A
# is the pen and SELECT+R the layout. Ids and addresses are not reused.
# SELECT Combos (id 7 at 0x50000000, 2026-10-28; id 1 was "SELECT + L/R"
# with L/R swap options) became two switches the same day (after
# #746): SELECT + L/R (previous/next layout) and SELECT + A/B/X/Y (touch
# mode), each On or Off; Off, those buttons reach the game with SELECT.
# Rotation (id 8) is "Screen Rotation"; menu order : the two SELECT
# switches, Screen Rotation, Cursor Speed.
SETTINGS = [
    # option labels : what the combo does, or Off
    ('SELECT + L/R', 9, 0x5000_0014, 0, 1, 0, [
        (0, 'Swap Screens'), (1, 'Off')]),
    ('SELECT + A/B/X/Y', 10, 0x5000_0018, 1, 1, 0, [
        (0, 'Toggle Touch'), (1, 'Off')]),
    # Rotation (2026-10-28, docs/screen-orientation.md): the stacked layout through the APF scaler's
    # rotated modes 2 (Left) and 3 (Right) for book-style games
    ('Screen Rotation', 8, 0x5000_0010, 4, 2, 0, [
        (0, 'Off'), (1, 'Left'), (2, 'Right')]),
    # Cursor Speed: Slow 1, Normal 3, Fast 6 px/frame (the maintainer wants it faster;
    # ids 3 and 5 were earlier speed sets, so a new id resets saved positions)
    ('Cursor Speed', 6, 0x5000_0008, 2, 2, 1, [
        (0, 'Slow'), (1, 'Normal'), (2, 'Fast')]),
]
PACKET_BITS = 6
MAX_LABEL = 18


def interact_variables():
    out = []
    for name, vid, addr, _, _, default, options in SETTINGS:
        out.append({'name': name, 'id': vid, 'type': 'list', 'enabled': True, 'persist': True,
                    'writeonly': True, 'address': f'0x{addr:08X}',
                    'defaultval': [v for v, _ in options].index(default),
                    'options': [{'value': v, 'name': t} for v, t in options]})
    return out


def svh():
    lines = ['// Generated by tools/ds/settings.py: do not edit.',
             '// Core Settings: bridge word index (address[7:2] of 0x500000xx), packet bit, width.',
             f'localparam integer SET_BITS = {PACKET_BITS};']
    default = 0
    for name, _, addr, bit, width, dv, _ in SETTINGS:
        tag = name.upper().replace(' + ', '_').replace('/', '').replace(' ', '_')
        lines.append(f'localparam integer SET_{tag}_IDX = {(addr & 0xFF) >> 2}, SET_{tag}_BIT = {bit}, '
                     f'SET_{tag}_W = {width};   // "{name}"')
        default |= dv << bit
    lines.append(f"localparam [SET_BITS-1:0] SET_DEFAULT = {PACKET_BITS}'h{default:02X};")
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--svh')
    ap.add_argument('--check')
    a = ap.parse_args()
    for name, _, addr, bit, width, dv, options in SETTINGS:
        assert addr >> 8 == 0x500000 and bit + width <= PACKET_BITS and dv in [v for v, _ in options], name
        assert all(v < 1 << width for v, _ in options), name
        for label in [name] + [t for _, t in options]:
            assert len(label) <= MAX_LABEL, f'menu label too long ({len(label)} > {MAX_LABEL}): {label!r}'
    if a.svh:
        open(a.svh, 'w').write(svh())
    if a.check:
        if open(a.check).read() != svh():
            sys.exit(f'{a.check} is stale: run tools/ds/settings.py --svh {a.check}')


if __name__ == '__main__':
    main()
