"""Write src/romlist.rs, the save types of melonDS's game list
(references/melonDS/src/ROMList.cpp, GPL-3.0-or-later, the melonDS team):
(game code, SaveMemType) per entry, sorted by game code.

  python3 scripts/romlist.py [path/to/ROMList.cpp]
"""
from pathlib import Path
import re
import subprocess
import sys

PLUGIN = Path(__file__).resolve().parents[1]
REPO = PLUGIN.parents[1]


def source():
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    for root in (REPO, REPO.parents[2]):
        p = root / 'references/melonDS/src/ROMList.cpp'
        if p.is_file():
            return p
    sys.exit('references/melonDS is not checked out')


def main():
    src = source()
    rev = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=src.parent, capture_output=True, text=True).stdout.strip() or 'unknown'
    entries = [(int(c, 16), int(t, 16)) for c, _, t in re.findall(r'\{(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+)\}', src.read_text())]
    codes = [c for c, _ in entries]
    if codes != sorted(codes) or len(set(codes)) != len(codes):
        sys.exit('ROMList is not sorted by unique game code')
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by scripts/romlist.py from melonDS src/ROMList.cpp',
        f'// (melonDS {rev[:12]}, Copyright 2016-2026 melonDS team, GPL-3.0-or-later).',
        '// (game code, melonDS SaveMemType); 0xFF stands for 0xFFFFFFFF. Do not edit.',
        '',
        f'pub const ROMLIST: [(u32, u8); {len(entries)}] = [',
    ]
    lines += [f'    (0x{c:08X}, {min(t, 0xFF)}),' for c, t in entries]
    lines += ['];', '']
    (PLUGIN / 'src/romlist.rs').write_text('\n'.join(lines))
    print(f'{len(entries)} entries from {src}')


if __name__ == '__main__':
    main()
