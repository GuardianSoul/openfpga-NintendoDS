#!/usr/bin/env python3
"""Position-independent ARMv4T fetch kernels; SDK envelope owned by hwref."""
from pathlib import Path
import json
r=Path(__file__).resolve().parent
cases=[]
for off in [0,4,8,12]:cases.append(dict(name=f'alu_o{off}',kind='alu',offset=off,stride=4,nodes=64,checksum=64))
for stride in [4,16,32]:
 for off in [0,4,8,12]:cases.append(dict(name=f'b_s{stride}_o{off}',kind='branch',offset=off,stride=stride,nodes=64,checksum=0))
for n in [2,3]:cases.append(dict(name=f'ring{n}_s16',kind='ring',offset=0,stride=16,nodes=n,checksum=64))
a=['/* Generated by gen.py. ARM7 ABI: r0=positive loop count; return checksum. */','.syntax unified','.arm','.text']
for j,c in enumerate(cases):
 n='af_'+c['name'];c.update(id=j,symbol=n,body_symbol=n+'_body',end_symbol=n+'_end',units_per_loop=64,unit='round' if c['kind']=='ring' else 'op')
 a+=['.balign 32',f'.global {n}, {n}_body, {n}_end',f'.type {n}, %function',n+':',' mov r3, r0']
 if c['kind']=='ring':a+=[' mov r3, r3, lsl #6']
 a+=[' mov r0, #0']
 if c['kind']=='alu':a+=[' mov r1, #1']
 a+=['.balign 16']+[' nop']*(c['offset']//4)+[n+'_body:']
 if c['kind']=='alu':a+=[' add r0, r0, r1']*64
 elif c['kind']=='branch':
  for k in range(64):
   a += [f'.L{n}_{k}:',f' b .L{n}_{k+1}' if k<63 else f' b .L{n}_end']
   a+=[' nop']*(c['stride']//4-1)
  a+=[f'.L{n}_end:']
 else:
  for k in range(c['nodes']):
   a+=[f'.L{n}_{k}:']
   if k<c['nodes']-1:a+=[f' b .L{n}_{k+1}']+[' nop']*3
   else:a+=[' subs r3, r3, #1',' add r0, r0, #1',f' bne .L{n}_0',' bx lr']
 if c['kind']!='ring':a+=[' subs r3, r3, #1',f' bne {n}_body',' bx lr']
 a += [n+'_end:',f'.size {n}, {n}_end-{n}']
(r/'kernels.S').write_text('\n'.join(a)+'\n')
h=['/* Generated by gen.py; ARM7 table only. */','#pragma once','#include <stdint.h>',
   '#define AF_CASES 18','typedef uint32_t (*A7FetchKernel)(uint32_t loops);',
   'typedef struct { const char *name; A7FetchKernel entry; const uint32_t *body, *end;',
   ' uint16_t checksum_per_loop; uint8_t id, kind, offset, stride, nodes; } A7FetchCase;',
   'enum { AF_ALU, AF_BRANCH, AF_RING };']
for c in cases:h += [f'extern uint32_t {c["symbol"]}(uint32_t);',f'extern const uint32_t {c["body_symbol"]}[], {c["end_symbol"]}[];']
h+=['extern const A7FetchCase af_cases[AF_CASES];'];(r/'kernels.h').write_text('\n'.join(h)+'\n')
csrc=['/* Generated by gen.py. */','#include "kernels.h"','const A7FetchCase af_cases[AF_CASES] = {']
for c in cases:csrc += [' {"%s",%s,%s,%s,%d,%d,%s,%d,%d,%d},'%(c['name'],c['symbol'],c['body_symbol'],c['end_symbol'],c['checksum'],c['id'],'AF_'+c['kind'].upper(),c['offset'],c['stride'],c['nodes'])]
csrc+=['};'];(r/'kernels.c').write_text('\n'.join(csrc)+'\n');(r/'cases.json').write_text(json.dumps(cases,indent=2)+'\n')
print('generated18 ARM7 kernels; no compiler/native/hardware invocation')
